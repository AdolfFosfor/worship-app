export const messages: Record<AppLocale, MessageDict> = { ru, ro, en }

export function translate(
  locale: AppLocale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const template = messages[locale][key] ?? messages.en[key] ?? messages.ru[key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`))
}

/** Known session/setlist title templates — localize display without touching song titles. */
const SESSION_TITLE_KEYS = ['setlists.defaultTitle'] as const

export function localizeSessionTitle(title: string, locale: AppLocale): string {
  const trimmed = title.trim()
  if (!trimmed) return title
  for (const key of SESSION_TITLE_KEYS) {
    for (const loc of Object.keys(messages) as AppLocale[]) {
      if (messages[loc][key] === trimmed) {
        return translate(locale, key)
      }
    }
  }
  return title
}
